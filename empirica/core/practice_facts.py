"""The generated, static part of a practice's instructions: ``.empirica/practice-facts.md``.

A practice's ``CLAUDE.md`` is written by people and grows by approved diffs. This file says what the practice's own data
already says, so every practice has instructions from its first session: who it is on the mesh, what kind of practice it
is, and how work is judged in its domain. The practice's ``CLAUDE.md`` imports it (``@.empirica/practice-facts.md``).

It is part of the context's cached front, so its bytes change only when its inputs do (David, 2026-11-08): no timestamps,
no counts that move, and ``write`` leaves the file alone when the text is unchanged. What changes every session
(calibration, due items, mail) arrives later, as session-start context.
"""

from __future__ import annotations

from pathlib import Path

FILE = Path(".empirica") / "practice-facts.md"


def _project(project_path: Path) -> dict | None:
    import yaml

    try:
        data = yaml.safe_load((project_path / ".empirica" / "project.yaml").read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError):
        return None
    return data if isinstance(data, dict) else None


def _domain_lines(project_path: Path, domain: str) -> list[str]:
    from empirica.config.domain_registry import DomainRegistry

    entry = DomainRegistry(project_path=project_path).get_domain_entry(domain)
    if entry is None:
        return [f"`{domain}` names no domain file on this machine, so no domain checks apply here."]
    lines = [f"**{entry.name}**: {entry.description}".rstrip()]
    if entry.hints_to_ai:
        lines += ["", "In this domain:"] + [f"- {hint}" for hint in entry.hints_to_ai]
    lines += ["", "What a transaction is checked for, by criticality:"]
    for level in ("low", "medium", "high", "critical"):
        checklist = entry.criticalities.get(level)
        if checklist is None:
            continue
        required = ", ".join(checklist.required) or "nothing beyond the loop itself"
        lines.append(f"- {level}: {required}")
    return lines


def render(project_path: Path | str) -> str:
    """The facts as markdown. A pure function of project.yaml and the domain file: the same inputs give the same bytes."""
    from empirica.core.project_types import TYPE_MEANINGS

    project_path = Path(project_path)
    data = _project(project_path) or {}
    name = str(data.get("name") or project_path.name)
    ai_id = str(data.get("ai_id") or name)
    seat = data.get("canonical_seat")
    description = str(data.get("description") or "").strip()
    project_type = str(data.get("type") or "").strip()
    domain = str(data.get("domain") or "").strip()

    out = [
        "<!-- Generated by empirica from .empirica/project.yaml and the domain file. Do not edit: it is rewritten when"
        " they change. The practice's own instructions belong in CLAUDE.md. -->",
        "",
        f"# This practice: {name}",
        "",
        f"- **ai_id:** `{ai_id}`" + (f"; on the mesh `{seat}`" if seat else ""),
    ]
    if description:
        out.append(f"- **For:** {description}")
    if project_type:
        meaning = TYPE_MEANINGS.get(project_type)
        out.append(f"- **Kind:** `{project_type}`" + (f": {meaning}" if meaning else ""))
    else:
        out.append("- **Kind:** not set. Set it with `empirica project-update --type TYPE`.")
    out += ["", "## How work is judged here", ""]
    if domain:
        out += _domain_lines(project_path, domain)
    else:
        out.append(
            "No domain is set, so transactions start from the kind's default. Set one with"
            " `empirica project-update --domain NAME`."
        )
    out += [
        "",
        "Calibration, due items and mail arrive at session start; they change every session and are not kept here.",
        "",
    ]
    return "\n".join(out)


def write(project_path: Path | str) -> bool:
    """Write the facts file if its text changed. True when written. A directory with no project file gets nothing."""
    project_path = Path(project_path)
    if _project(project_path) is None:
        return False
    text = render(project_path)
    target = project_path / FILE
    try:
        if target.read_text(encoding="utf-8") == text:
            return False
    except OSError:
        pass
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp = target.with_suffix(".md.tmp")
        tmp.write_text(text, encoding="utf-8")
        tmp.replace(target)
    except OSError:
        return False
    return True


# ── the CLAUDE.md seed: the authored part, started for a practice that has none ─────────────────────────────────────────
#
# A practice's CLAUDE.md is its own instructions, written with the person and committed. A new practice gets a short seed
# shaped by its kind; it imports the generated facts above and grows by lines the practitioner proposes and the person
# approves. Nothing personal is copied in (the workflow protocol is per person and loads at session start; this file is
# committed). An existing CLAUDE.md, in either place Claude Code reads one, is never touched.

_NOT_WRITTEN = "Not written yet: ask the person, then propose the text."

_SECTIONS = {
    "software": ("How it is built and tested", "What must not break", "How changes are reviewed and released"),
    "content": ("Voice and audience", "Where it is published, and who approves", "Sources and claims"),
    "research": ("Questions it answers", "Sources and how claims are cited", "What counts as done"),
    "operations": (
        "Machines and services it touches",
        "What needs a person before it changes",
        "How a change is undone",
    ),
    "general": ("What good work looks like here", "What needs a person's approval", "Where its work goes"),
}


def _family(project_type: str) -> str:
    from empirica.core.project_types import SOFTWARE_TYPES

    if project_type in SOFTWARE_TYPES:
        return "software"
    if project_type in ("content", "research", "operations"):
        return project_type
    return "general"


def seed_claude_md(project_path: Path | str) -> Path | None:
    """Write a CLAUDE.md seed for a practice that has none. Returns its path, or None when one exists or nothing was written."""
    project_path = Path(project_path)
    if (project_path / "CLAUDE.md").exists() or (project_path / ".claude" / "CLAUDE.md").exists():
        return None
    data = _project(project_path)
    if data is None:
        return None
    name = str(data.get("name") or project_path.name)
    description = str(data.get("description") or "").strip()
    lines = [
        f"# {name}",
        "",
        "@.empirica/practice-facts.md",
    ]
    if (project_path / "AGENTS.md").exists():
        lines.append("@AGENTS.md")
    lines += [
        "",
        "<!-- This practice's own instructions. Each section starts unwritten; when you learn something durable about how",
        "this practice works, propose the line as a diff and write it only once the person approves. Rules, not history:",
        "say what holds now, not how it came to be. The facts imported above are generated; do not copy them here. -->",
        "",
        "## What this practice is for",
        "",
        description if description and not description.endswith(" project") else _NOT_WRITTEN,
    ]
    for title in _SECTIONS[_family(str(data.get("type") or ""))]:
        lines += ["", f"## {title}", "", _NOT_WRITTEN]
    target = project_path / "CLAUDE.md"
    try:
        target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    except OSError:
        return None
    return target


# ── established practices: the facts at session start until the practice's CLAUDE.md imports them ─────────────────────

IMPORT_LINE = "@.empirica/practice-facts.md"


def _imports_facts(project_path: Path) -> bool | None:
    """True when a CLAUDE.md here imports the facts file, False when one exists without it, None when there is none."""
    found = None
    for candidate in (project_path / "CLAUDE.md", project_path / ".claude" / "CLAUDE.md"):
        try:
            text = candidate.read_text(encoding="utf-8")
        except OSError:
            continue
        found = False
        if "practice-facts.md" in text:
            return True
    return found


def session_block(project_path: Path | str) -> str:
    """What session start adds for this practice: refresh the facts file, and when the practice's CLAUDE.md does not import it
    yet, the facts themselves with the one-line import offered. A practice whose CLAUDE.md imports them gets nothing here: they
    already load from the cached front. The CLAUDE.md is never edited from here; the person approves the change."""
    project_path = Path(project_path)
    if _project(project_path) is None:
        return ""
    write(project_path)
    imports = _imports_facts(project_path)
    if imports:
        return ""
    if imports is None:
        offer = (
            "This practice has no CLAUDE.md. Offer the person one: a heading, the line `"
            + IMPORT_LINE
            + "` so these facts load"
            " from the cached front of the context, and the practice's own sections; write it only once they approve."
        )
    else:
        offer = (
            "This practice's CLAUDE.md does not import these facts, so they arrive here, after the cached part of the context."
            " Offer the person a one-line diff adding `"
            + IMPORT_LINE
            + "` near the top of CLAUDE.md; apply it only once they"
            " approve."
        )
    facts = "\n".join(line for line in render(project_path).splitlines() if not line.startswith("<!--")).strip()
    # A plain first line: the session banner shows only the first line of these notices.
    return "This practice's facts (generated from .empirica/project.yaml):\n\n" + facts + "\n\n" + offer
